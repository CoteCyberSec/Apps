    fun isValidThemeId(id: String): Boolean {
        if (id.isEmpty()) return true
        if (id.length > 40) return false
        if (presets.any { it.id == id }) return true
        return id.matches(Regex("^custom_[0-9A-Fa-f]{6}$"))
    }

    fun formatCustomThemeId(argb: Int): String {
        val rgb = argb and 0x00FFFFFF
        return "custom_%06X".format(rgb)
    }

    fun parseCustomRgb(id: String): Int? {
        if (!id.matches(Regex("^custom_[0-9A-Fa-f]{6}$"))) return null
        val hex = id.removePrefix("custom_")
        return (0xFF000000L or hex.toLong(16)).toInt()
    }

    fun findPreset(id: String?): CoupleAestheticPreset {
        return presets.firstOrNull { it.id == id } ?: presets.first()
    }
